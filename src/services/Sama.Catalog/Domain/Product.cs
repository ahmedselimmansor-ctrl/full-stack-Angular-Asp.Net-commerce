using NpgsqlTypes;
using Sama.Shared.Kernel.Domain;
using Sama.Shared.Kernel.Primitives;
using Sama.Shared.Messaging.Contracts;

namespace Sama.Catalog.Domain;

public enum ProductStatus
{
    Draft = 0,
    Published = 1,
    Archived = 2,
}

/// <summary>
/// A sellable item. Price lives here; stock does not — inventory is owned by its own service,
/// so a catalogue read never blocks on the system that reserves units during checkout.
/// </summary>
public sealed class Product : AggregateRoot<Guid>, ITenantScoped, IAuditable, ISoftDeletable
{
    private readonly List<ProductImage> _images = [];

    private Product() { }

    private Product(
        Guid id,
        Guid tenantId,
        string sku,
        string name,
        string slug,
        string description,
        Guid categoryId,
        decimal price,
        string currency)
        : base(id)
    {
        TenantId = tenantId;
        Sku = sku;
        Name = name;
        Slug = slug;
        Description = description;
        CategoryId = categoryId;
        Price = price;
        Currency = currency;
        Status = ProductStatus.Draft;
    }

    public Guid TenantId { get; private set; }

    /// <summary>Merchant-facing identifier. Unique per tenant.</summary>
    public string Sku { get; private set; } = string.Empty;

    public string Name { get; private set; } = string.Empty;

    /// <summary>
    /// The Arabic name, when the buyer has supplied one.
    ///
    /// Nullable rather than required: a product is often created in one language
    /// and translated later, and blocking publication on a missing translation
    /// would mean an untranslated item cannot be sold at all. The storefront falls
    /// back to <see cref="Name"/>, so the worst case is a mixed-script listing
    /// rather than a blank one.
    /// </summary>
    public string? NameAr { get; private set; }

    public string Slug { get; private set; } = string.Empty;

    public string Description { get; private set; } = string.Empty;

    public string? DescriptionAr { get; private set; }

    public Guid CategoryId { get; private set; }

    public string? Brand { get; private set; }

    /// <summary>
    /// Stored as a plain decimal plus its currency code rather than as a mapped value object:
    /// keeping the column primitive keeps it indexable and filterable in SQL. <see cref="AsMoney"/>
    /// rebuilds the value object for domain use.
    /// </summary>
    public decimal Price { get; private set; }

    public string Currency { get; private set; } = "USD";

    public ProductStatus Status { get; private set; }

    public IReadOnlyCollection<ProductImage> Images => _images.AsReadOnly();

    /// <summary>
    /// PostgreSQL-maintained full-text index over name, brand and description. Generated by the
    /// database, so it can never drift from the row the way an application-maintained copy would.
    /// </summary>
    public NpgsqlTsVector SearchVector { get; private set; } = null!;

    public DateTimeOffset CreatedAt { get; private set; }
    public Guid? CreatedBy { get; private set; }
    public DateTimeOffset? UpdatedAt { get; private set; }
    public Guid? UpdatedBy { get; private set; }

    public bool IsDeleted { get; private set; }
    public DateTimeOffset? DeletedAt { get; private set; }
    public Guid? DeletedBy { get; private set; }

    public Money AsMoney() => Money.FromTrusted(Price, Currency);

    public static Product Create(
        Guid tenantId,
        string sku,
        string name,
        string slug,
        string description,
        Guid categoryId,
        Money price,
        string? brand = null,
        string? nameAr = null,
        string? descriptionAr = null)
    {
        var product = new Product(
            SamaId.New(), tenantId, sku, name, slug, description, categoryId, price.Amount, price.Currency)
        {
            Brand = brand,
            NameAr = Normalise(nameAr),
            DescriptionAr = Normalise(descriptionAr),
        };

        return product;
    }

    /// <summary>
    /// Blank and whitespace-only translations are stored as null.
    ///
    /// An empty string and "no translation" are the same thing to a reader, but
    /// they are different to the fallback: an empty string would satisfy a
    /// null-check and render a product with no name at all.
    /// </summary>
    private static string? Normalise(string? value) =>
        string.IsNullOrWhiteSpace(value) ? null : value.Trim();

    public void UpdateDetails(
        string name,
        string slug,
        string description,
        Guid categoryId,
        string? brand,
        string? nameAr = null,
        string? descriptionAr = null)
    {
        Name = name;
        Slug = slug;
        Description = description;
        CategoryId = categoryId;
        Brand = brand;
        NameAr = Normalise(nameAr);
        DescriptionAr = Normalise(descriptionAr);
    }

    /// <summary>
    /// Changes the price and announces it. Downstream this evicts CDN and Redis entries and
    /// lets Ordering distinguish a price change from a stale cached read.
    /// </summary>
    public void ChangePrice(Money newPrice)
    {
        if (newPrice.IsNegative)
        {
            throw new ArgumentException("A product price cannot be negative.", nameof(newPrice));
        }

        var oldPrice = Price;
        if (oldPrice == newPrice.Amount && string.Equals(Currency, newPrice.Currency, StringComparison.Ordinal))
        {
            return;
        }

        Price = newPrice.Amount;
        Currency = newPrice.Currency;

        Raise(new ProductPriceChanged(Id, TenantId, oldPrice, newPrice.Amount, newPrice.Currency));
    }

    public void Publish()
    {
        if (Status == ProductStatus.Published)
        {
            return;
        }

        if (_images.Count == 0)
        {
            throw new InvalidOperationException("A product needs at least one image before it can be published.");
        }

        Status = ProductStatus.Published;
        Raise(new ProductPublished(Id, TenantId, Sku));
    }

    public void Archive() => Status = ProductStatus.Archived;

    public void AddImage(string url, string? altText, int sortOrder)
        => _images.Add(new ProductImage(Id, url, altText, sortOrder));

    public void ClearImages() => _images.Clear();

    public void SetCreated(DateTimeOffset at, Guid? by) { CreatedAt = at; CreatedBy = by; }
    public void SetUpdated(DateTimeOffset at, Guid? by) { UpdatedAt = at; UpdatedBy = by; }

    public void MarkDeleted(DateTimeOffset at, Guid? by)
    {
        IsDeleted = true;
        DeletedAt = at;
        DeletedBy = by;
        Status = ProductStatus.Archived;
    }
}

public sealed class ProductImage
{
    private ProductImage() { }

    public ProductImage(Guid productId, string url, string? altText, int sortOrder)
    {
        ProductId = productId;
        Url = url;
        AltText = altText;
        SortOrder = sortOrder;
    }

    public Guid ProductId { get; private set; }

    /// <summary>Path in the media bucket. Served through Cloud CDN, never proxied by this service.</summary>
    public string Url { get; private set; } = string.Empty;

    public string? AltText { get; private set; }

    public int SortOrder { get; private set; }
}
